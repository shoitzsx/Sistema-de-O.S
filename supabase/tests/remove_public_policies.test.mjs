// Valida a migration num PostgreSQL descartável (PGlite), com um esqueleto do
// schema observado em produção. Nada aqui toca o banco real.
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';

const [migrationPath, rollbackPath] = process.argv.slice(2);
const db = new PGlite();
let failures = 0;

const setup = `
create role anon nologin; create role authenticated nologin; create role service_role nologin;
create schema auth; create schema storage;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid', true), '')::uuid $$;
grant usage on schema auth, storage, public to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;

create table public.users (id bigint primary key, name text, username text, password text, role text, auth_user_id uuid);
create table public.machines (id bigint generated by default as identity primary key, name text);
create table public.parts_tools (id bigint primary key);
create table public.service_orders (id bigint primary key, operator_id bigint, assigned_user_id bigint);
create table public.checklists (id bigint primary key);
create table public.checklist_templates (id bigint primary key);
create table public.checklist_schedules (id bigint primary key);
create table public.audit_logs (id bigint generated by default as identity primary key, action text, entity_type text, entity_id bigint, details jsonb, user_id bigint, user_name text, user_role text, created_at timestamp default now());
create table public.role_permissions (id bigint primary key);
create table public.user_permissions (id bigint primary key);
create table storage.objects (id bigint generated by default as identity primary key, bucket_id text, name text);

do $$ declare t text; begin
  foreach t in array array['users','machines','parts_tools','service_orders','checklists','checklist_templates','checklist_schedules','audit_logs','role_permissions','user_permissions'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('grant all on public.%I to anon, authenticated', t);
  end loop;
end $$;
alter table storage.objects enable row level security;
grant all on storage.objects to anon, authenticated;
grant usage on all sequences in schema public, storage to anon, authenticated;

create function public.is_admin_user() returns boolean language sql stable security definer set search_path to 'public'
  as $$ select exists (select 1 from public.users where auth_user_id = auth.uid() and lower(role) in ('admin','administrador')) $$;
create function public.current_app_user_id() returns bigint language sql stable security definer set search_path to 'public'
  as $$ select id from public.users where auth_user_id = auth.uid() limit 1 $$;
create function public.rls_auto_enable() returns event_trigger language plpgsql security definer set search_path to 'pg_catalog'
  as $$ begin null; end $$;
grant execute on function public.is_admin_user(), public.current_app_user_id() to anon, authenticated;

-- policies como observadas em produção (2026-10-23)
create policy "Admins manage machines" on public.machines for all to authenticated using (is_admin_user()) with check (is_admin_user());
create policy "Authenticated users can read machines" on public.machines for select to authenticated using (true);
create policy "Allow public read machines table" on public.machines for select using (true);
create policy "Allow public insert machines table" on public.machines for insert with check (true);
create policy "Allow public update machines table" on public.machines for update using (true) with check (true);
create policy "Allow public delete machines table" on public.machines for delete using (true);
create policy "Admins read audit logs" on public.audit_logs for select to authenticated using (is_admin_user());
create policy "Allow public read audit logs" on public.audit_logs for select using (true);
create policy "Allow public insert audit logs" on public.audit_logs for insert with check (true);
create policy "Authenticated users insert audit logs" on public.audit_logs for insert to authenticated with check (true);
create policy "Users read related service orders" on public.service_orders for select to authenticated
  using (is_admin_user() or operator_id = current_app_user_id() or coalesce(assigned_user_id, -1) = current_app_user_id());
create policy "Allow public read machines bucket" on storage.objects for select using (bucket_id = 'machines');
create policy "Allow public upload machines bucket" on storage.objects for insert with check (bucket_id = 'machines');
create policy "Allow public update machines bucket" on storage.objects for update using (bucket_id = 'machines') with check (bucket_id = 'machines');
create policy "Allow public delete machines bucket" on storage.objects for delete using (bucket_id = 'machines');
create policy "Allow public read manuals bucket" on storage.objects for select using (bucket_id = 'manuals');
create policy "Allow public upload manuals bucket" on storage.objects for insert with check (bucket_id = 'manuals');
create policy "Allow public update manuals bucket" on storage.objects for update using (bucket_id = 'manuals') with check (bucket_id = 'manuals');
create policy "Allow public delete manuals bucket" on storage.objects for delete using (bucket_id = 'manuals');

-- dados fictícios
insert into public.users values
  (1, 'Admin Teste', 'admin', 'x', 'admin', '00000000-0000-0000-0000-000000000001'),
  (2, 'Operador A', 'opa', 'x', 'operator', '00000000-0000-0000-0000-000000000002'),
  (3, 'Operador B', 'opb', 'x', 'operator', '00000000-0000-0000-0000-000000000003');
insert into public.machines (name) values ('Trator 1');
insert into public.service_orders values (10, 2, null), (20, 3, null);
insert into public.audit_logs (action, entity_type, entity_id, user_id) values
  ('service_order_closed', 'service_orders', 10, 2),
  ('service_order_closed', 'service_orders', 20, 3),
  ('user_created', 'users', 1, 1);
insert into storage.objects (bucket_id, name) values ('manuals', 'm.pdf'), ('machines', 'f.jpg');
`;

const ADMIN = '00000000-0000-0000-0000-000000000001';
const OPA = '00000000-0000-0000-0000-000000000002';

async function as(role, uid, sql) {
  await db.exec('reset role');
  await db.exec(`select set_config('test.uid', '${uid ?? ''}', false)`);
  await db.exec(`set role ${role}`);
  try {
    const r = await db.query(sql);
    return { ok: true, rows: r.rows, affected: r.affectedRows };
  } catch (e) {
    return { ok: false, error: e.message };
  } finally {
    await db.exec('reset role');
  }
}

function check(name, cond, detail) {
  console.log(`${cond ? 'PASS' : 'FAIL'}  ${name}${cond ? '' : '  -> ' + JSON.stringify(detail)}`);
  if (!cond) failures++;
}

async function expectations(label) {
  console.log(`\n--- ${label} ---`);
  let r;
  r = await as('anon', null, 'select count(*)::int n from public.machines');
  check('anon não lê machines', !r.ok || r.rows[0].n === 0, r);
  r = await as('anon', null, "insert into public.machines (name) values ('x')");
  check('anon não insere machines', !r.ok, r);
  r = await as('anon', null, 'delete from public.machines');
  check('anon não apaga machines', !r.ok || r.affected === 0, r);
  r = await as('anon', null, 'select count(*)::int n from public.audit_logs');
  check('anon não lê audit_logs', !r.ok || r.rows[0].n === 0, r);
  r = await as('anon', null, "insert into public.audit_logs (action, user_id) values ('forjado', 1)");
  check('anon não insere audit_logs', !r.ok, r);
  r = await as('anon', null, "insert into storage.objects (bucket_id, name) values ('manuals', 'malware.exe')");
  check('anon não envia arquivo', !r.ok, r);
  r = await as('anon', null, 'delete from storage.objects');
  check('anon não apaga arquivo', !r.ok || r.affected === 0, r);

  r = await as('authenticated', OPA, 'select count(*)::int n from public.machines');
  check('operador lê machines', r.ok && r.rows[0].n >= 1, r);
  r = await as('authenticated', OPA, "insert into public.machines (name) values ('x')");
  check('operador não insere machines', !r.ok, r);
  r = await as('authenticated', OPA, "insert into public.audit_logs (action, entity_type, entity_id, user_id) values ('service_order_updated', 'service_orders', 10, 2)");
  check('operador registra log em nome próprio', r.ok, r);
  r = await as('authenticated', OPA, "insert into public.audit_logs (action, user_id) values ('forjado', 1)");
  check('operador não registra log em nome de outro', !r.ok, r);
  r = await as('authenticated', OPA, 'select entity_id from public.audit_logs order by id');
  check('operador lê só logs das próprias OS', r.ok && r.rows.length > 0 && r.rows.every((x) => Number(x.entity_id) === 10), r);
  r = await as('authenticated', OPA, "insert into storage.objects (bucket_id, name) values ('manuals', 'y.pdf')");
  check('operador não envia arquivo', !r.ok, r);
  r = await as('authenticated', OPA, 'select count(*)::int n from storage.objects');
  check('operador lista arquivos', r.ok && r.rows[0].n >= 2, r);

  r = await as('authenticated', ADMIN, "insert into public.machines (name) values ('Trator 2')");
  check('admin insere machines', r.ok, r);
  r = await as('authenticated', ADMIN, "update public.machines set name = name || '!' where name = 'Trator 2'");
  check('admin altera machines', r.ok && r.affected === 1, r);
  r = await as('authenticated', ADMIN, 'select count(*)::int n from public.audit_logs');
  check('admin lê todos os logs', r.ok && r.rows[0].n >= 4, r);
  r = await as('authenticated', ADMIN, "insert into storage.objects (bucket_id, name) values ('machines', 'z.jpg')");
  check('admin envia arquivo', r.ok, r);
  r = await as('authenticated', ADMIN, "update storage.objects set name = 'z2.jpg' where name = 'z.jpg'");
  check('admin substitui arquivo (upsert)', r.ok && r.affected === 1, r);
  r = await as('authenticated', ADMIN, "delete from storage.objects where name = 'z2.jpg'");
  check('admin apaga arquivo', r.ok && r.affected === 1, r);

  const left = await db.query("select tablename, policyname from pg_policies where 'public' = any(roles) or 'anon' = any(roles)");
  check('nenhuma policy para public/anon', left.rows.length === 0, left.rows);
}

await db.exec(setup);
const before = await as('anon', null, "insert into public.machines (name) values ('prova')");
check('[antes] anon CONSEGUE inserir machines (reproduz o problema)', before.ok, before);

await db.exec(readFileSync(migrationPath, 'utf8'));
await expectations('depois da migration');

await db.exec(readFileSync(rollbackPath, 'utf8'));
const afterRollback = await as('anon', null, "insert into public.machines (name) values ('prova2')");
check('[rollback] volta ao estado anterior', afterRollback.ok, afterRollback);

await db.exec(readFileSync(migrationPath, 'utf8'));
await expectations('reaplicada depois do rollback');

console.log(`\n${failures === 0 ? 'OK' : 'FALHAS: ' + failures}`);
process.exit(failures === 0 ? 0 : 1);
